import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source=await fs.readFile(new URL('../app/challenges.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {challengeDefinitions:defs,challengesFor}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
assert.equal(defs.length,70);
assert.equal(new Set(defs.map(b=>b.id)).size,70);
assert.deepEqual([1,2,3,4,5].map(l=>defs.filter(b=>b.level===l).length),[24,14,14,9,9]);
assert.equal(challengesFor([]).filter(b=>b.earned).length,0);
const row=(date,payload,kind='workout')=>({date,payload,kind});
const get=(rows,id)=>challengesFor(rows).find(b=>b.id===id);
const run=[row('2026-10-01',{name:'Run',movementType:'cardio',cardioType:'run',miles:25,minutes:60})];
assert.equal(get(run,'monthly-twenty-five').earned,true);
assert.equal(get([...run,row('2026-11-01',{name:'Run',cardioType:'run',miles:25})],'monthly-fifty').earned,false);
assert.equal(get([...run,row('2026-10-02',{name:'Run',cardioType:'run',miles:25})],'monthly-fifty').earned,true);
assert.equal(get([row('2026-10-01',{name:'Run',cardioType:'indoor-bike',miles:500})],'first-miles').earned,true);
assert.equal(get([row('2026-10-01',{name:'Indoor bike',cardioType:'indoor-bike',minutes:30})],'cycling-start').earned,true);
assert.equal(get([row('2026-10-01',{name:'Squat',movementType:'strength',sets:10})],'ten-sets').earned,true);
assert.equal(get([row('2026-10-01',{name:'Run',movementType:'cardio',sets:10})],'ten-sets').earned,false);
assert.equal(get([row('2026-10-01',{name:'Walking lunge',movementType:'strength',cardioType:'other',minutes:30})],'walking-start').earned,false);
assert.equal(get([row('2026-10-01',{name:'Yoga'}),row('2026-10-02',{name:'Mobility'}),row('2026-10-03',{name:'Stretching'})],'recovery-start').earned,true);
const week=Array.from({length:7},(_,i)=>row('2026-10-'+String(i+1).padStart(2,'0'),{name:'Walk',minutes:30}));
assert.equal(get(week,'perfect-exercise-week').earned,true);
assert.equal(get(week.filter((_,i)=>i!==3),'perfect-exercise-week').earned,false);
assert.equal(get([week[0],week[0],week[0]],'three-workout-days').earned,false);
const balanced=week.slice(0,3).flatMap(r=>[r,row(r.date,{name:'Lunch'},'meal')]);
assert.equal(get(balanced,'balanced-start').earned,true);
assert.equal(get([row('2026-02-30',{minutes:50000})],'fifty-thousand-minutes').earned,false);
const earned=get(run,'first-miles');
const award=row('2026-10-12',{badgeId:'first-miles',earnedOn:'2026-10-12'},'challengeBadge');
assert.equal(get([...run,award],'first-miles').earnedOn,'2026-10-12');
assert.equal(get([award],'first-miles').earned,false);
assert.equal(earned.xp,300);
assert.deepEqual([1,2,3,4,5].map(l=>defs.find(b=>b.level===l).xp),[300,1000,3000,10000,30000]);
console.log('PASS: 70 unique badges, 24/14/14/9/9 levels, monthly boundaries, typed cardio, strength, recovery, streak gaps, date deduplication, balance, invalid dates and award removal.');
